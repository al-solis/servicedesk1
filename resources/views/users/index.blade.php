<script>
    document.querySelectorAll('.toggle-status').forEach(toggle => {
        toggle.addEventListener('change', function () {
            let userId = this.getAttribute('data-id');
            let newStatus = this.checked ? 'Active' : 'Inactive';
            
            fetch(`/users/toggle-status/${userId}`, {
                method: 'POST',
                headers: {
                    'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]').getAttribute('content'),
                    'Content-Type': 'application/json'
                },
                body: JSON.stringify({ status: newStatus })
            })
            .then(response => response.json())
            .then(data => {
                if (data.success) {
                    this.closest('label').querySelector('.status-text').innerText = data.status;
                } else {
                    alert(data.message); // Display error message if any
                    this.checked = !this.checked; // Revert the toggle
                }
            });
        });
    });
    </script>
</script>


